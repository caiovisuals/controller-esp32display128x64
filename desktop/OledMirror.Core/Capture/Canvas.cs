    public static ReadOnlySpan<byte> Glyph(char c)
    {
        c = Fold(c);
        if (c < First || c > Last) c = '?';
        return Data.AsSpan((c - First) * GlyphWidth, GlyphWidth);
    }

    public static char Fold(char c)
    {
        if (c is >= First and <= Last) return c;
        if (c == '\t' || c == '\u00A0') return ' ';
        if (c is '\u00B0' or '\u00BA') return 'o'; // grau e ordinal
        if (c == '\u00AA') return 'a';
        if (c is '\u2018' or '\u2019') return '\'';
        if (c is '\u201C' or '\u201D') return '"';
        if (c is '\u2013' or '\u2014') return '-';

        string decomposed = c.ToString().Normalize(System.Text.NormalizationForm.FormD);
        return decomposed.Length > 0 && decomposed[0] is >= First and <= Last ? decomposed[0] : '?';
    }
